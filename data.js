/* Демо-дані: вигадані інвестори, вклади й щомісячні виплати.
   Формат рядка такий самий, як у CSV для імпорту. */
window.SAMPLE_ROWS = (function () {
  var investors = [
    ['Олена Ковальчук', 'Депозит 12 міс', 25000, 17],
    ['Андрій Мельник', 'Депозит 6 міс', 12000, 14],
    ['Ірина Бондар', 'Стратегія Growth', 40000, 21],
    ['Максим Шевчук', 'Депозит 12 міс', 18500, 17],
    ['Наталія Ткаченко', 'Депозит 6 міс', 8000, 14],
    ['Сергій Кравець', 'Стратегія Growth', 60000, 21],
    ['Юлія Олійник', 'Депозит 12 міс', 32000, 17],
    ['Дмитро Лисенко', 'Депозит 6 міс', 15000, 14]
  ];
  var months = ['2026-05', '2026-06', '2026-07', '2026-08', '2026-09', '2026-10'];

  /* Навмисні помилки, щоб звірці було що знайти */
  var wrong = {
    'Сергій Кравець|2026-08': 1000.00,   /* виплатили 1000 замість 1050 */
    'Юлія Олійник|2026-09': 543.33,      /* переставили цифри */
    'Андрій Мельник|2026-10': 280.00     /* виплатили двічі */
  };
  var pending = { 'Ірина Бондар|2026-10': true, 'Дмитро Лисенко|2026-10': true };

  var rows = [];
  investors.forEach(function (inv) {
    months.forEach(function (m) {
      var expected = Math.round(inv[2] * inv[3] / 12) / 100;
      var key = inv[0] + '|' + m;
      var paid = pending[key] ? '' : (wrong[key] !== undefined ? wrong[key] : expected);
      rows.push({ date: m + '-05', investor: inv[0], product: inv[1], amount: inv[2], rate: inv[3], paid: paid });
    });
  });
  return rows;
})();
